# Arora V exposes initialized BSRAM via SP (UG300 section 3.2). Use the
# documented primitive explicitly: this avoids inference falling back to LUTs.
def primitive_rom(name,data,width,addr_bits):
    words=16384//width;low_bits=int(math.log2(words));banks=(len(data)+words-1)//words
    bank_bits=max(1,addr_bits-low_bits)
    out=[f'module {name}(input clk,input [{addr_bits-1}:0] address,output [{width-1}:0] data);',
         f'wire [31:0] bank_data[0:{banks-1}];reg [{bank_bits-1}:0] bank_q=0;',
         f'always @(posedge clk)bank_q<='+(f'address[{addr_bits-1}:{low_bits}];' if banks>1 else "0;")]
    for bank in range(banks):
        contents=data[bank*words:(bank+1)*words];contents+=[0]*(words-len(contents))
        if not any(contents):out.append(f'assign bank_data[{bank}]=0;');continue
        chunks=[];per=256//width
        for k in range(64):
            val=sum(contents[k*per+j]<<(width*j) for j in range(per))
            if val:chunks.append(f'.INIT_RAM_{k:02X}(256\'h{val:064x})')
        out.append(f'SP #(.BIT_WIDTH({width}),.READ_MODE(1\'b0),.WRITE_MODE(2\'b00),'+','.join(chunks)+f') bank_{bank}(')
        out.append(f'.DO(bank_data[{bank}]),.DI(32\'d0),.BLKSEL(3\'d0),.AD({{address[{low_bits-1}:0],{14-low_bits}\'d0}}),')
        ce=f'address[{addr_bits-1}:{low_bits}]=={bank}' if banks>1 else "1'b1"
        out.append(f'.WRE(1\'b0),.CLK(clk),.CE({ce}),.OCE(1\'b1),.RESET(1\'b0));')
    out.append(f'assign data=bank_data[bank_q][{width-1}:0];\nendmodule')
    return '\n'.join(out)
